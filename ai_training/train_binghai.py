from ultralytics import YOLO

if __name__ == '__main__':
    print("正在加载 YOLOv8 图像分类引擎 (防过拟合加固版)...")
    # 保持使用分类专属预训练模型
    model = YOLO("yolov8n-cls.pt")

    print("🔥 天衍·区域化农业病理大模型 V2.0 稳健性训练启动...")

    results = model.train(
        # 1. 核心数据集根目录路径 (已更新为 D 盘路径)
        data=r"D:\-EcoNexus-\ai_training\datasets\crop_disease_dataset",

        # 2. 基础训练控制
        epochs=50,  # 可以适当设大，因为有早停机制把关
        imgsz=224,
        batch=32,
        project="runs/classify",
        name="tianyan_disease_v2_regional-4",

        # ================== 防过拟合 ==================

        val=True,  # 开启验证，早停机制依赖验证集的表现

        # 【策略 A：早停机制 (Early Stopping)】
        # 如果连续 8 个 Epoch 验证集上的 top1_acc（准确率）没有提升，
        # 训练将自动提前终止，死死卡住模型开始死记硬背的临界点。
        patience=8,

        # 【策略 B：全连接层 Dropout 正则化】
        # 在分类头（Linear Layer）前随机丢弃 20% 的神经元权重，
        # 强迫模型利用组合特征进行判别，这是应对小样本过拟合的绝杀技。
        dropout=0.2,

        # 【策略 C：标签平滑 (Label Smoothing)】
        # 将硬标签（0或1）转化为软标签（如0.025和0.9),
        # 防止模型在训练后期对某些特定样本过度自信，能极大提升模型的泛化能力。
        label_smoothing=0.1,

        # 【策略 D：权重衰减 (L2 正则化)】
        # 适当提高权重衰减系数（默认0.0005），惩罚过大的权重值，让模型边界更平滑。
        weight_decay=0.001,

        # ================== 🌪️ 极限空间/色彩数据增强 ==================
        # 通过在内存中动态裂变图片，让模型在有限的数据下看到无限的可能
        hsv_h=0.015,  # 色调轻微色差（模拟不同相机传感器偏色）
        hsv_s=0.7,  # 饱和度大幅调整（模拟强逆光与暴晒）
        hsv_v=0.6,  # 亮度大幅调整（模拟阴天、多云、树荫遮挡）
        degrees=30.0,  # 随机旋转（模拟无人机巡检时的不同拍摄视角）
        fliplr=0.5,  # 50% 概率左右翻转
        flipud=0.5,  # 50% 概率上下翻转（应对叶片反转或倒伏情况）
        erasing=0.2,  # 20% 概率在图片上随机涂抹马赛克方块（模拟局部叶片被挡住）
    )

    print("✅ 稳健性训练完成！已生成具备极强抗干扰与泛化能力的新一代“医学大脑”！")